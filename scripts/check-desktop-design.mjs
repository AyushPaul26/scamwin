import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { chromium } from 'playwright';
import { neon } from '@neondatabase/serverless';
import { createBotSandbox, deleteBotSandbox } from '../lib/daytona.ts';
import { createPreviewContext } from './creature-preview-session.mjs';
import { decrypt } from '../node_modules/@auth0/nextjs-auth0/dist/server/cookies.js';
const base = process.argv[2] ?? 'http://localhost:3000';
const browser = await chromium.launch();
const context = await createPreviewContext(browser, base, { viewport: { width: 1440, height: 1000 } });
const owner = (await decrypt((await context.cookies()).find(c => c.name === '__session').value, process.env.AUTH0_SECRET)).payload.user.sub;
const sql = neon(process.env.DATABASE_URL);
const bot = randomUUID(), chat = randomUUID();
let sandbox;
try {
  sandbox = await createBotSandbox(bot);
  await sql`INSERT INTO bots(id,user_id,name,avatar,job,instructions,sandbox_id) VALUES (${bot},${owner},'Atlas','atlas','Developer','Help with tasks.',${sandbox})`;
  await sql`INSERT INTO chats(id,user_id,kind) VALUES (${chat},${owner},'direct')`;
  await sql`INSERT INTO chat_members(chat_id,bot_id) VALUES (${chat},${bot})`;
  const page = await context.newPage(); page.setDefaultTimeout(120000);
  await page.goto(`${base}/chats/${chat}`);
  await page.getByRole('button', { name: 'Open computer desktop', exact: true }).click();
  await page.getByText('Atlas has control', { exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('.desktop-frame')?.getBoundingClientRect().height > 200);
  await page.waitForFunction(() => document.querySelector('.desktop-frame canvas')?.width > 0);
  // The VNC handshake precedes the first framebuffer paint.
  await page.waitForTimeout(1500);
  await page.screenshot({ path: '/tmp/openmods-desktop-split.png' });
  let connections = 0;
  page.on('websocket', () => connections++);
  const divider = page.getByRole('separator', { name: 'Resize computer panel' });
  const edge = await divider.boundingBox();
  const before = await page.locator('.desktop-panel').evaluate(e => e.getBoundingClientRect().width);
  await page.mouse.move(edge.x, edge.y + 180);
  await page.mouse.down();
  await page.mouse.move(edge.x - 120, edge.y + 180, { steps: 8 });
  await page.mouse.up();
  const after = await page.locator('.desktop-panel').evaluate(e => e.getBoundingClientRect().width);
  assert.ok(after > before + 100, `drag expands the computer: before=${before}, after=${after}, value=${await divider.getAttribute('aria-valuenow')}`);
  await divider.focus();
  await page.keyboard.press('Home');
  assert.equal(await divider.getAttribute('aria-valuenow'), '30');
  await page.keyboard.press('ArrowLeft');
  assert.equal(await divider.getAttribute('aria-valuenow'), '32');
  await page.keyboard.press('End');
  assert.equal(await divider.getAttribute('aria-valuenow'), '70');
  assert.equal(connections, 0, 'resizing retains the connection');

  await page.getByRole('button', { name: 'Take over', exact: true }).click();
  await page.getByText('You have control', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Release control', exact: true }).click();
  await page.getByRole('button', { name: 'Enter fullscreen', exact: true }).click();
  await page.locator('[data-chat-composer-container] textarea').fill('Draft stays while switching views');
  await page.waitForFunction(() => document.querySelector('.desktop-panel')?.getBoundingClientRect().width > 1000);
  await page.screenshot({ path: '/tmp/openmods-desktop-expanded.png' });
  assert.equal(connections, 0);
  await page.getByRole('button', { name: 'Exit fullscreen', exact: true }).click();
  assert.equal(await page.locator('[data-chat-composer-container] textarea').inputValue(), 'Draft stays while switching views');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector('.desktop-panel')?.getBoundingClientRect().width > 380);
  await page.screenshot({ path: '/tmp/openmods-desktop-mobile.png' });
  const overflows = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflows, false);
  await page.getByRole('button', { name: 'Take over', exact: true }).click();
  await page.getByText('You have control', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Release control', exact: true }).click();
  await page.getByRole('button', { name: 'Reconnect desktop', exact: true }).click();
  await page.getByText('Atlas has control', { exact: true }).waitFor();
  assert.equal(connections, 1);
  await page.getByRole('button', { name: 'Close desktop', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Open computer desktop', exact: true }).evaluate(e => e === document.activeElement), true);
  console.log('PASS real Daytona desktop: split/expanded/mobile, drag and keyboard resize, takeover/release, persistent connection and draft, reconnect, close focus');
} finally {
  await browser.close();
  await sql`DELETE FROM chats WHERE id=${chat}`;
  await sql`DELETE FROM bots WHERE id=${bot}`;
  if (sandbox) await deleteBotSandbox(sandbox);
}
